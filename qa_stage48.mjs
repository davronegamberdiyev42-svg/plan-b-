import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { auditVocabulary, containsLexicalItem, scheduleVocabularyReview, validateDailyVocabularyCompletion, VOCAB_ENGINE_VERSION } from '../assets/js/core/vocabulary-engine.js';

const full = { id: 1, word: 'significant', meaning_en: 'important', uzbek: 'muhim', example: 'A significant change occurred.', part_of_speech: 'adjective', ipa_us: '/sɪɡˈnɪfɪkənt/', ipa_uk: '/sɪɡˈnɪfɪkənt/' };
const data = auditVocabulary([full, { id: 2, word: 'art', ipa_us: '/ɑːrt/', ipa_uk: '' }, { id: 3, word: 'party', translation_mode: 'pronunciation_index_only', ipa_us: '/ˈpɑːrti/' }], [{ word_ids: [1, 2, 3] }]);
assert.equal(VOCAB_ENGINE_VERSION, '48.0.0');
assert.equal(validateDailyVocabularyCompletion(6,2,12), true);
assert.equal(validateDailyVocabularyCompletion(5,2,12), false);
assert.equal(validateDailyVocabularyCompletion(8,1,12), false);
assert.equal(validateDailyVocabularyCompletion(8,2,11), false);
assert.equal(data.indexed, 3);
assert.equal(data.dailyUniqueItems, 3);
assert.equal(data.dailyCoreComplete, 1);
assert.equal(data.dailyCoreWithBothIpa, 1);
assert.equal(data.dailyCoreMissingIpaIds.length, 2);
assert.equal(data.pronunciationOnlyEntries, 1);
assert.equal(data.duplicateNormalisedTerms, 0);

assert.equal(containsLexicalItem('The party lasted all night.', 'art'), false);
assert.equal(containsLexicalItem('The arts shape public debate.', 'art'), false);
assert.equal(containsLexicalItem('The data showed a significant difference.', 'significant'), true);
assert.equal(containsLexicalItem('A long-term plan worked.', 'long term'), true);
assert.equal(containsLexicalItem('The plan is long-term.', 'long-term'), true);
assert.equal(containsLexicalItem('Drifting off during a lecture.', 'drift off'), false);
assert.equal(containsLexicalItem('The meeting may drift off topic.', 'drift off'), true);
assert.equal(containsLexicalItem('A discrepancy, not a similarity.', 'discrepancy'), true);
assert.equal(containsLexicalItem('The art-based course is useful.', 'art'), true);

const now = new Date('2026-11-08T12:00:00');
const again = scheduleVocabularyReview({ count: 3, intervalDays: 6, ease: 2.4 }, 'again', now);
assert.equal(again.intervalDays, 0);
assert.equal(again.due, '2026-11-08');
assert.equal(again.count, 0);
assert.equal(again.lapses, 1);
const hard = scheduleVocabularyReview({}, 'hard', now);
assert.equal(hard.intervalDays, 1);
assert.equal(hard.count, 1);
const good1 = scheduleVocabularyReview({}, 'good', now);
assert.equal(good1.intervalDays, 1);
const good2 = scheduleVocabularyReview(good1, 'good', now);
assert.equal(good2.intervalDays, 6);
const easy = scheduleVocabularyReview({}, 'easy', now);
assert.equal(easy.intervalDays, 4);
assert.ok(easy.ease > 2.3);
let history = {};
for (let i = 0; i < 25; i++) history = scheduleVocabularyReview(history, 'good', now);
assert.equal(history.history.length, 20);
assert.equal(history.repetitions, history.count);
assert.throws(() => scheduleVocabularyReview({}, 'maybe', now), /Unsupported SRS rating/);

